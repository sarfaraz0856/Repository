"""Measure the narration clips, fit them into exactly 60 s (1800 frames), and write:
  src/timing.ts          scene start/length + voice offset per scene (frames)
  public/audio/voice.wav narration only
  public/audio/mix.wav   narration + music bed + UI sound effects, ducked, -14 LUFS
  out/claude_ai_sample_60sec.hi.srt  Hindi-Hinglish subtitles
Usage: python tools/build_audio.py <clips_dir>   (clips named md5(text).wav, texts in voiceover/narration.json)
"""
import hashlib, json, os, subprocess, sys
import numpy as np, soundfile as sf

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CLIPS = sys.argv[1]
SR, FPS, TOTAL = 48000, 30, 1800
TEXTS = json.load(open(os.path.join(ROOT, "voiceover", "narration.json"), encoding="utf-8"))
LEAD, VOICE_AT, TAIL, MAX_TEMPO = 0.4, 0.2, 1.6, 1.15   # seconds; TAIL = silence after the last line for the fade-out

def load(text, tempo):
    f = os.path.join(CLIPS, hashlib.md5(text.encode()).hexdigest() + ".wav")
    af = "silenceremove=start_periods=1:start_threshold=-45dB,areverse,silenceremove=start_periods=1:start_threshold=-45dB,areverse"
    if abs(tempo - 1) > 0.005: af = f"atempo={tempo:.4f}," + af
    raw = subprocess.run(["ffmpeg", "-v", "error", "-i", f, "-af", af, "-ac", "1", "-ar", str(SR), "-f", "f32le", "-"], capture_output=True, check=True).stdout
    return np.frombuffer(raw, np.float32).copy()

# 1) choose the gentlest tempo that fits; minimum natural gap between lines 0.35 s
tempo = 1.0
while True:
    clips = [load(t, tempo) for t in TEXTS]
    speech = sum(len(c) for c in clips) / SR
    need = LEAD + speech + 0.35 * (len(clips) - 1) + TAIL
    if need <= TOTAL / FPS or tempo >= MAX_TEMPO: break
    tempo = min(MAX_TEMPO, tempo * (need / (TOTAL / FPS)) + 0.005)
gap = (TOTAL / FPS - LEAD - speech - TAIL) / (len(clips) - 1)
if gap < 0.2: sys.exit(f"Narration too long even at {tempo:.2f}x: shorten the script")

# 2) layout: each scene starts VOICE_AT before its line; the last scene runs to the end
starts, t = [], LEAD
for c in clips:
    starts.append(t); t += len(c) / SR + gap
scene_from = [0] + [round((s - VOICE_AT) * FPS) for s in starts[1:]]
scenes = []
for i, fr in enumerate(scene_from):
    end = scene_from[i + 1] if i + 1 < len(scene_from) else TOTAL
    scenes.append(dict(fr=fr, dur=end - fr, voiceAt=round(starts[i] * FPS) - fr))
with open(os.path.join(ROOT, "src", "timing.ts"), "w") as f:
    f.write("// Generated by tools/build_audio.py from the measured narration. Frame numbers at 30 fps.\n")
    f.write(f"// Narration tempo {tempo:.3f}x, gap between lines {gap:.2f}s.\nexport const FPS = {FPS};\nexport const TOTAL = {TOTAL};\nexport const SCENES = [\n")
    for s in scenes: f.write(f"  {{ from: {s['fr']}, dur: {s['dur']}, voiceAt: {s['voiceAt']} }},\n")
    f.write("];\n")

# 3) audio
N = int(TOTAL / FPS * SR); voice = np.zeros(N, np.float32); vmask = np.zeros(N, np.float32)
for s, c in zip(starts, clips):
    a = int(s * SR); b = min(N, a + len(c)); voice[a:b] += c[:b - a]; vmask[a:b] = 1
voice /= np.abs(voice).max() + 1e-9
rng = np.random.default_rng(7)
def tone(fq, amp, dec, ln, f2=None):
    tt = np.arange(int(ln * SR)) / SR; fr = fq if f2 is None else fq + (f2 - fq) * tt / ln
    return (amp * np.sin(2 * np.pi * np.cumsum(np.full_like(tt, 1.0) * fr) / SR) * np.exp(-dec * tt)).astype(np.float32)
def noise(ln, lo, hi, amp):
    n = int(ln * SR); x = rng.standard_normal(n); X = np.fft.rfft(x); fq = np.fft.rfftfreq(n, 1 / SR)
    X[(fq < lo) | (fq > hi)] = 0; y = np.fft.irfft(X, n); env = np.sin(np.linspace(0, np.pi, n)) ** 2
    return (y / (np.abs(y).max() + 1e-9) * env * amp).astype(np.float32)
sfx = np.zeros(N, np.float32)
def put(sig, sec, g=1.0):
    a = int(sec * SR); b = min(N, a + len(sig))
    if 0 <= a < N: sfx[a:b] += g * sig[:b - a]
whoosh, click, tick, pop = noise(.55, 250, 3500, .14), tone(2100, .18, 90, .06) + tone(1050, .1, 60, .06), tone(3600, .035, 160, .03), tone(700, .07, 30, .12, 1050)
for s in scenes[1:]: put(whoosh, s["fr"] / FPS - 0.15)
s3, s4 = scenes[2]["fr"] / FPS, scenes[3]["fr"] / FPS
put(click, s3 + 32 / FPS); put(click, s3 + 92 / FPS)                               # cursor clicks in the Projects scene
for k in range(23): put(tick, s3 + (110 + k * 1.6) / FPS)                           # typing the project name
for k in range(3): put(pop, s3 + (176 + k * 34 + 30) / FPS, .8)                      # upload complete
for k in range(46): put(tick, s4 + (12 + k * 1.3) / FPS)                            # typing the prompt
for k in range(3): put(pop, s4 + (150 + k * 22) / FPS, .8)                           # result cards
s5 = scenes[4]; st = max(1, round(s5["dur"] / 6))
for k in range(4): put(pop, (s5["fr"] + 38 + k * st) / FPS, .8)                      # skills switching on
chime = np.zeros(int(1.6 * SR), np.float32)
for i, fq in enumerate([523.25, 659.25, 783.99, 1046.5]):
    c = tone(fq, .1, 4, 1.2); a = int(i * .1 * SR); chime[a:a + len(c)] += c
put(chime, scenes[6]["fr"] / FPS + 0.3, .9)
# music: soft pad + gentle arpeggio in a minor-ish progression, 90 bpm
beat = 60 / 90; bar = 4 * beat; prog = [[220.0, 261.63, 329.63], [174.61, 220.0, 261.63], [196.0, 246.94, 293.66], [164.81, 207.65, 246.94]]
music = np.zeros(N, np.float32)
for ci in range(int(TOTAL / FPS / bar) + 1):
    a = int(ci * bar * SR)
    if a >= N: break
    ch = prog[ci % 4]; b = min(N, a + int(bar * SR)); tt = np.arange(b - a) / SR
    env = np.minimum(1, tt / .6) * np.minimum(1, (bar - tt) / .7)
    pad = sum(np.sin(2 * np.pi * fq * tt) + .45 * np.sin(2 * np.pi * fq * 1.004 * tt) + .15 * np.sin(2 * np.pi * 2 * fq * tt) for fq in ch)
    music[a:b] += (pad * env * .035).astype(np.float32)
    for j in range(8):
        fq = ch[j % 3] * (4 if j % 4 == 3 else 2); p = a + int(j * beat / 2 * SR); pl = tone(fq, .03, 6, .5); e = min(N, p + len(pl))
        if p < N: music[p:e] += pl[:e - p]
ker = np.ones(int(.35 * SR)) / int(.35 * SR); vm = np.convolve(vmask, ker, mode="same")
music *= (1 - .65 * np.clip(vm, 0, 1)).astype(np.float32)
ta = np.arange(N) / SR; fade = np.minimum(1, ta / 1.2) * np.minimum(1, (TOTAL / FPS - ta) / 1.5)
mix = (voice + sfx * .7 + music * .55) * fade.astype(np.float32); mix /= np.abs(mix).max() + 1e-9
os.makedirs(os.path.join(ROOT, "public", "audio"), exist_ok=True); os.makedirs(os.path.join(ROOT, "out"), exist_ok=True)
sf.write(os.path.join(ROOT, "public", "audio", "voice.wav"), voice * .9, SR)
raw = os.path.join(ROOT, "out", "mix_raw.wav"); sf.write(raw, np.stack([mix, mix], 1) * .95, SR)
subprocess.run(["ffmpeg", "-v", "error", "-y", "-i", raw, "-af", "loudnorm=I=-14:TP=-1.5:LRA=11", "-ar", str(SR), os.path.join(ROOT, "public", "audio", "mix.wav")], check=True)
os.remove(raw)
def ts(x):
    ms = int(round(x * 1000)); h, ms = divmod(ms, 3600000); m, ms = divmod(ms, 60000); s, ms = divmod(ms, 1000)
    return f"{h:02}:{m:02}:{s:02},{ms:03}"
with open(os.path.join(ROOT, "out", "claude_ai_sample_60sec.hi.srt"), "w", encoding="utf-8") as f:
    for k, (s, c, t) in enumerate(zip(starts, clips, TEXTS), 1): f.write(f"{k}\n{ts(s)} --> {ts(s + len(c) / SR)}\n{t}\n\n")
print(json.dumps(dict(tempo=round(tempo, 3), gap=round(gap, 2), speech=round(speech, 2), scenes=scenes)))
