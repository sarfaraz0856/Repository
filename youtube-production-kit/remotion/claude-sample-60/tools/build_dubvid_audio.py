"""Dub tutorial video: measure the narration clips (line_NNN.wav by line index), lay out every line
and scene, and write
  src/dub/timing.ts               scene + line frames, subtitle cues (30 fps)
  public/audio/dubvid_voice.wav   narration only
  public/audio/dubvid_mix.wav     narration + music bed + sound design, ducked, -14 LUFS
  out/dubvid.hi.srt
Usage: python tools/build_dubvid_audio.py <clips_dir> [tempo]
       python tools/build_dubvid_audio.py --estimate      (timing from text length, no audio)
"""
import hashlib, json, os, re, subprocess, sys
import numpy as np, soundfile as sf

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CLIPS = sys.argv[1]
EST = CLIPS == "--estimate"
TEMPO = float(sys.argv[2]) if len(sys.argv) > 2 else 1.0
SR, FPS = 48000, 30
LEAD, GAP, SCENE_GAP, TAIL = 1.2, 0.42, 1.1, 3.2
N = json.load(open(os.path.join(ROOT, "voiceover", "dub", "narration.json"), encoding="utf-8"))

def load(i, text):
    if EST: return np.zeros(int(len(text) / 13.0 * SR), np.float32)
    f = os.path.join(CLIPS, f"line_{i + 1:03d}.wav")
    if not os.path.exists(f): sys.exit(f"missing clip {f}")
    af = "silenceremove=start_periods=1:start_threshold=-45dB,areverse,silenceremove=start_periods=1:start_threshold=-45dB,areverse"
    if abs(TEMPO - 1) > 0.005: af = f"atempo={TEMPO:.4f}," + af
    raw = subprocess.run(["ffmpeg", "-v", "error", "-i", f, "-af", af, "-ac", "1", "-ar", str(SR), "-f", "f32le", "-"], capture_output=True, check=True).stdout
    return np.frombuffer(raw, np.float32).copy()

clips = [load(i, n["tts"]) for i, n in enumerate(N)]
lines, t, prev = [], LEAD, None
for n, c in zip(N, clips):
    if prev is not None: t += SCENE_GAP if n["scene"] != prev else GAP
    lines.append(dict(scene=n["scene"], start=t, dur=len(c) / SR, sub=n["sub"])); t += len(c) / SR; prev = n["scene"]
TOTAL_S = t + TAIL; TOTAL = int(round(TOTAL_S * FPS))
scenes = []
for sc in sorted({l["scene"] for l in lines}):
    first = next(l for l in lines if l["scene"] == sc)
    scenes.append(dict(scene=sc, fr=0 if sc == 1 else int(round((first["start"] - 0.45) * FPS))))
for i, s in enumerate(scenes): s["dur"] = (scenes[i + 1]["fr"] if i + 1 < len(scenes) else TOTAL) - s["fr"]

# subtitle cues: at most ~78 characters (two lines), split at punctuation, then at word boundaries
def chunks(text, maxc=78):
    parts = [p.strip() for p in re.split(r"(?<=[।?!,.:])\s+", text) if p.strip()]
    out = []
    for p in parts:
        if out and len(out[-1]) + 1 + len(p) <= maxc: out[-1] += " " + p
        elif len(p) <= maxc: out.append(p)
        else:
            cur = ""
            for w in p.split():
                if cur and len(cur) + 1 + len(w) > maxc: out.append(cur); cur = w
                else: cur = (cur + " " + w).strip()
            if cur: out.append(cur)
    return out
subs = []
for l in lines:
    cs = chunks(l["sub"]); tot = sum(len(c) for c in cs); s = l["start"]
    for c in cs:
        d = l["dur"] * len(c) / tot; subs.append(dict(a=s, b=s + d, text=c)); s += d

def F(x): return int(round(x * FPS))
with open(os.path.join(ROOT, "src", "dub", "timing.ts"), "w", encoding="utf-8") as f:
    f.write(f"// Generated by tools/build_dubvid_audio.py from the measured narration (tempo {TEMPO}x). 30 fps.\n")
    f.write(f"export const FPS = {FPS};\nexport const TOTAL = {TOTAL};\n")
    f.write("export const SCENES: { from: number; dur: number }[] = " + json.dumps([{"from": s["fr"], "dur": s["dur"]} for s in scenes]) + ";\n")
    f.write("export const LINES: { scene: number; from: number; dur: number }[] = " + json.dumps([{"scene": l["scene"], "from": F(l["start"]), "dur": max(1, F(l["dur"]))} for l in lines]) + ";\n")
    f.write("export const SUBS: { from: number; to: number; text: string }[] = " + json.dumps([{"from": F(s["a"]), "to": F(s["b"]) - 1, "text": s["text"]} for s in subs], ensure_ascii=False) + ";\n")

def ts(x):
    ms = int(round(x * 1000)); h, ms = divmod(ms, 3600000); m, ms = divmod(ms, 60000); s, ms = divmod(ms, 1000)
    return f"{h:02}:{m:02}:{s:02},{ms:03}"
os.makedirs(os.path.join(ROOT, "out"), exist_ok=True)
with open(os.path.join(ROOT, "out", "dubvid.hi.srt"), "w", encoding="utf-8") as f:
    for k, s in enumerate(subs, 1): f.write(f"{k}\n{ts(s['a'])} --> {ts(s['b'])}\n{s['text']}\n\n")

if EST: sys.exit(print(json.dumps(dict(estimate=True, frames=TOTAL, secs=round(TOTAL_S, 1)))))
# ---------------- audio ----------------
NS = int(TOTAL_S * SR); voice = np.zeros(NS, np.float32); vmask = np.zeros(NS, np.float32)
for l, c in zip(lines, clips):
    a = int(l["start"] * SR); b = min(NS, a + len(c)); voice[a:b] += c[:b - a]; vmask[a:b] = 1
voice /= np.abs(voice).max() + 1e-9
# de-glitch: silence isolated clicks/blips (<200 ms of sound with >=150 ms of silence on both sides)
H = int(SR * .01); m = NS // H
vdb = 20 * np.log10(np.sqrt((voice[:m * H].reshape(m, H) ** 2).mean(1)) + 1e-9); act = vdb > np.percentile(vdb, 99) - 40
edges = np.flatnonzero(np.diff(np.concatenate([[0], act.astype(np.int8), [0]])))
isl = list(zip(edges[::2], edges[1::2])); gmask = np.ones(NS, np.float32); nblip = 0
for k, (a, b) in enumerate(isl):
    pre = a - (isl[k - 1][1] if k else 0); post = (isl[k + 1][0] if k + 1 < len(isl) else m) - b
    if b - a < 20 and pre >= 15 and post >= 15: gmask[max(0, (a - 2) * H):(b + 2) * H] = 0; nblip += 1
fk = int(SR * .01); voice *= np.convolve(gmask, np.ones(fk) / fk, mode="same").astype(np.float32)
print("deglitched blips:", nblip)
rng = np.random.default_rng(7)
def tone(fq, amp, dec, ln, f2=None):
    tt = np.arange(int(ln * SR)) / SR; fr = fq if f2 is None else fq + (f2 - fq) * tt / ln
    return (amp * np.sin(2 * np.pi * np.cumsum(np.full_like(tt, 1.0) * fr) / SR) * np.exp(-dec * tt)).astype(np.float32)
def noise(ln, lo, hi, amp):
    n = int(ln * SR); x = rng.standard_normal(n); X = np.fft.rfft(x); fq = np.fft.rfftfreq(n, 1 / SR)
    X[(fq < lo) | (fq > hi)] = 0; y = np.fft.irfft(X, n); env = np.sin(np.linspace(0, np.pi, n)) ** 2
    return (y / (np.abs(y).max() + 1e-9) * env * amp).astype(np.float32)
sfx = np.zeros(NS, np.float32)
def put(sig, sec, g=1.0):
    a = int(sec * SR); b = min(NS, a + len(sig))
    if 0 <= a < NS: sfx[a:b] += g * sig[:b - a]
whoosh, pop = noise(.6, 250, 3500, .14), tone(700, .05, 30, .12, 1050)
impact = tone(55, .5, 3.5, 1.6)                                          # soft cinematic low hit at the start
put(impact, 0.25, .9)
for s in scenes[1:]: put(whoosh, s["fr"] / FPS - 0.12)
for l in lines: put(pop, l["start"] + 0.05, .55)                       # soft UI tick as each beat's elements appear
proc = np.concatenate([tone(1800 + 300 * (k % 3), .025, 60, .05) for k in range(10)])
for sc, k in ((5, 1),):                       # "processing" chirps where AI output appears
    l = [x for x in lines if x["scene"] == sc][k]; put(proc, l["start"] + 0.4, .8)
chime = np.zeros(int(1.6 * SR), np.float32)
for i, fq in enumerate([523.25, 659.25, 783.99, 1046.5]):
    c = tone(fq, .1, 4, 1.2); a = int(i * .1 * SR); chime[a:a + len(c)] += c
put(chime, [x for x in lines if x["scene"] == max(l["scene"] for l in lines)][-1]["start"] + 0.2, .9)
beat = 60 / 90; bar = 4 * beat
progs = [[[220.0, 261.63, 329.63], [174.61, 220.0, 261.63], [196.0, 246.94, 293.66], [164.81, 207.65, 246.94]],
         [[174.61, 220.0, 261.63], [196.0, 246.94, 293.66], [220.0, 261.63, 329.63], [246.94, 293.66, 369.99]]]
music = np.zeros(NS, np.float32)
for ci in range(int(TOTAL_S / bar) + 1):
    a = int(ci * bar * SR)
    if a >= NS: break
    ch = progs[(ci // 16) % 2][ci % 4]; b = min(NS, a + int(bar * SR)); tt = np.arange(b - a) / SR
    env = np.minimum(1, tt / .6) * np.minimum(1, (bar - tt) / .7)
    pad = sum(np.sin(2 * np.pi * fq * tt) + .45 * np.sin(2 * np.pi * fq * 1.004 * tt) + .15 * np.sin(2 * np.pi * 2 * fq * tt) for fq in ch)
    music[a:b] += (pad * env * .035).astype(np.float32)
    for j in range(8):
        fq = ch[j % 3] * (4 if j % 4 == 3 else 2); p = a + int(j * beat / 2 * SR); pl = tone(fq, .03, 6, .5); e = min(NS, p + len(pl))
        if p < NS: music[p:e] += pl[:e - p]
ker = np.ones(int(.35 * SR)) / int(.35 * SR); vm = np.convolve(vmask, ker, mode="same")
music *= (1 - .68 * np.clip(vm, 0, 1)).astype(np.float32)
ta = np.arange(NS) / SR; fade = np.minimum(1, ta / 1.0) * np.minimum(1, (TOTAL_S - ta) / 2.5)
mix = (voice + sfx * .7 + music * .5) * fade.astype(np.float32); mix /= np.abs(mix).max() + 1e-9
os.makedirs(os.path.join(ROOT, "public", "audio"), exist_ok=True)
sf.write(os.path.join(ROOT, "public", "audio", "dubvid_voice.wav"), voice * .9, SR)
raw = os.path.join(ROOT, "out", "dubvid_mix_raw.wav"); sf.write(raw, np.stack([mix, mix], 1) * .95, SR)
subprocess.run(["ffmpeg", "-v", "error", "-y", "-i", raw, "-af", "loudnorm=I=-14:TP=-1.5:LRA=11", "-ar", str(SR), os.path.join(ROOT, "public", "audio", "dubvid_mix.wav")], check=True)
os.remove(raw)
print(json.dumps(dict(tempo=TEMPO, total=f"{int(TOTAL_S // 60)}:{TOTAL_S % 60:05.2f}", frames=TOTAL, lines=len(lines), cues=len(subs),
                      scenes=[f"{s['scene']}@{s['fr'] / FPS / 60:.0f}:{(s['fr'] / FPS) % 60:04.1f}" for s in scenes])))
